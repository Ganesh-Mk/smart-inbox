-- -------------------------------------------------------------------------------------
-- 17. REVIEW_DECISION — the human's verdict on a message (R9, E40).
-- -------------------------------------------------------------------------------------
CREATE TABLE review_decision (
  id                    NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id            NUMBER(19)   NOT NULL,
  reviewer              VARCHAR2(200) NOT NULL,
  decision              VARCHAR2(20) NOT NULL,
  final_categories_json VARCHAR2(500),
  notes                 VARCHAR2(4000),
  decided_at            TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_review_message FOREIGN KEY (message_id)
    REFERENCES inbox_message (id) ON DELETE CASCADE,
  CONSTRAINT ck_review_decision CHECK (decision IN ('ACCEPT','OVERRIDE','REJECT'))
);


-- -------------------------------------------------------------------------------------
-- 18. PROCESSING_METRIC — per-stage timings behind the R17 batch report.
-- -------------------------------------------------------------------------------------
CREATE TABLE processing_metric (
  id           NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_type VARCHAR2(20) NOT NULL,
  subject_id   NUMBER(19)   NOT NULL,
  stage        VARCHAR2(40) NOT NULL,
  duration_ms  NUMBER(10)   NOT NULL,
  succeeded    CHAR(1)      DEFAULT 'Y' NOT NULL,
  created_at   TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_metric_succeeded CHECK (succeeded IN ('Y','N'))
);


-- -------------------------------------------------------------------------------------
-- 19–20. Literature screening (bonus, §4 of the brief). CASE_RECORD already carries
--        case_index, so these two tables are the entire persistence cost of the bonus.
-- -------------------------------------------------------------------------------------
CREATE TABLE literature_batch (
  id            NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_name    VARCHAR2(200),
  uploaded_by   VARCHAR2(200),
  file_count    NUMBER(6)    DEFAULT 0 NOT NULL,
  status        VARCHAR2(30) DEFAULT 'RECEIVED' NOT NULL,
  created_at    TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_lit_batch_status CHECK (status IN ('RECEIVED','SCREENING','DONE','FAILED'))
);

CREATE TABLE literature_item (
  id                NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id          NUMBER(19)   NOT NULL,
  document_id       NUMBER(19),
  filename          VARCHAR2(500),
  is_case_report    CHAR(1)      DEFAULT 'N' NOT NULL,
  confidence        NUMBER(5,4)  DEFAULT 0 NOT NULL,
  relevance_reason  VARCHAR2(2000),
  case_count        NUMBER(6)    DEFAULT 0 NOT NULL,
  excluded_sections VARCHAR2(1000),
  status            VARCHAR2(30) DEFAULT 'PENDING' NOT NULL,
  error_text        VARCHAR2(2000),
  ai_call_id        NUMBER(19),
  created_at        TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_lit_item_batch FOREIGN KEY (batch_id)
    REFERENCES literature_batch (id) ON DELETE CASCADE,
  CONSTRAINT fk_lit_item_document FOREIGN KEY (document_id)
    REFERENCES document (id) ON DELETE CASCADE,
  CONSTRAINT ck_lit_item_case_report CHECK (is_case_report IN ('Y','N')),
  CONSTRAINT ck_lit_item_status CHECK (status IN ('PENDING','SCREENING','DONE','FAILED'))
);
