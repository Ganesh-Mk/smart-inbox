--     The API key never appears here (CLAUDE.md constraint 3).
-- -------------------------------------------------------------------------------------
CREATE TABLE ai_call_log (
  id                NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id            NUMBER(19),
  correlation_id    VARCHAR2(64),
  purpose           VARCHAR2(60) NOT NULL,
  model             VARCHAR2(100) NOT NULL,
  prompt_version    VARCHAR2(40),
  request_json      CLOB,
  response_json     CLOB,
  prompt_tokens     NUMBER(10) DEFAULT 0 NOT NULL,
  completion_tokens NUMBER(10) DEFAULT 0 NOT NULL,
  cached_tokens     NUMBER(10) DEFAULT 0 NOT NULL,
  cache_write_tokens NUMBER(10) DEFAULT 0 NOT NULL,
  cost_usd          NUMBER(12,8) DEFAULT 0 NOT NULL,
  latency_ms        NUMBER(10),
  http_status       NUMBER(5),
  retries           NUMBER(4)  DEFAULT 0 NOT NULL,
  repaired          CHAR(1)    DEFAULT 'N' NOT NULL,
  created_at        TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_ai_call_repaired CHECK (repaired IN ('Y','N'))
);


