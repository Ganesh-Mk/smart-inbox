-- =====================================================================================
-- Smart Inbox — V1: tables
--
-- PROJECT_PLAN §9.1–9.3. Eighteen application tables plus two for the literature bonus.
--
-- Two conventions run through the whole schema and both exist for a regulatory reason:
--
--   * APPEND-ONLY.  Nothing a reviewer touches is ever updated in place. CLASSIFICATION and
--     EXTRACTED_FIELD carry a SUPERSEDED_BY self-reference: an override inserts a new row and
--     points the old one at it. The AI's original answer therefore survives forever, which is
--     what a 21 CFR Part 11-style system requires (E40).
--
--   * EVIDENCE IS A ROW, NOT A STRING.  Every extracted fact hangs FIELD_EVIDENCE rows that
--     carry the quote, its character offsets, a bounding box and — crucially — a VERIFIED flag
--     written by code that proved the quote exists in the source. The model's own citation is
--     never trusted (E27).
--
-- Y/N flags are CHAR(1) with a CHECK rather than a boolean, so the schema reads identically
-- from SQL*Plus, JDBC and the Flyway history on every supported Oracle version.
-- =====================================================================================


-- -------------------------------------------------------------------------------------
-- 1. INBOX_MESSAGE — one row per email pulled from the mailbox.
-- -------------------------------------------------------------------------------------
CREATE TABLE inbox_message (
  id              NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- E2: idempotent polling. Message-ID header when present, else a SHA-256 of
  -- (from, subject, sent_at, normalised body). The unique constraint makes re-processing
  -- impossible by construction rather than by convention.
  dedupe_key      VARCHAR2(200) NOT NULL,
  message_id_hdr  VARCHAR2(500),
  folder          VARCHAR2(200) DEFAULT 'INBOX' NOT NULL,
  imap_uid        NUMBER(19),
  sender_email    VARCHAR2(320),
  sender_name     VARCHAR2(320),
  recipient_email VARCHAR2(320),
  subject         VARCHAR2(1000),
  sent_at         TIMESTAMP(6) WITH TIME ZONE,
  received_at     TIMESTAMP(6) WITH TIME ZONE,
  body_text       CLOB,
  body_html       CLOB,
  body_charset    VARCHAR2(60),
  -- E10: character offset in body_text at which the quoted reply/forward history begins.
  -- NULL means no quoted section was detected. New text before this offset is the primary
  -- source; quoted text after it is retained but never counted as an independent report.
  quoted_offset   NUMBER(10),
  status          VARCHAR2(30)  DEFAULT 'RECEIVED' NOT NULL,
  needs_attention CHAR(1)       DEFAULT 'N' NOT NULL,
  attention_reason VARCHAR2(500),
  created_at      TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at      TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_inbox_message_dedupe UNIQUE (dedupe_key),
  CONSTRAINT ck_inbox_message_status CHECK (status IN (
    'RECEIVED','PARSING','PARSED','CLASSIFYING','CLASSIFIED','EXTRACTING',
    'READY_FOR_REVIEW','REVIEWED','NEEDS_ATTENTION','FAILED')),
  CONSTRAINT ck_inbox_message_attn CHECK (needs_attention IN ('Y','N'))
);

COMMENT ON TABLE inbox_message IS 'One email pulled over IMAP. dedupe_key is the E2 idempotency key.';


-- -------------------------------------------------------------------------------------
-- 2. MESSAGE_ATTACHMENT — every part we found, including the ones we deliberately skip.
-- -------------------------------------------------------------------------------------
CREATE TABLE message_attachment (
  id             NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id     NUMBER(19)    NOT NULL,
  filename       VARCHAR2(500),
  -- E4: the declared type and the sniffed type are stored separately on purpose. They
  -- disagreeing (a PDF sent as application/octet-stream) is itself audit-interesting.
  declared_type  VARCHAR2(200),
  sniffed_type   VARCHAR2(200),
  size_bytes     NUMBER(19)    DEFAULT 0 NOT NULL,
  sha256         VARCHAR2(64),
  blob_path      VARCHAR2(1000),
  -- E5: 0 = attached directly, 1 = hoisted out of a message/rfc822 forward.
  nesting_level  NUMBER(3)     DEFAULT 0 NOT NULL,
  processed      CHAR(1)       DEFAULT 'N' NOT NULL,
  -- E6: non-PDF types are logged with a reason rather than silently dropped.
  skip_reason    VARCHAR2(200),
  created_at     TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_attachment_message FOREIGN KEY (message_id)
    REFERENCES inbox_message (id) ON DELETE CASCADE,
  CONSTRAINT ck_attachment_processed CHECK (processed IN ('Y','N')),
  CONSTRAINT ck_attachment_skip CHECK (skip_reason IS NULL OR skip_reason IN (
    'UNSUPPORTED_TYPE','TOO_LARGE','ENCRYPTED','CORRUPT','EMPTY',
    'DUPLICATE_CONTENT','NESTING_TOO_DEEP'))
);


-- -------------------------------------------------------------------------------------
-- 3. DOCUMENT — the unit of understanding. An email body is a document too (E11), so
--    bodies and PDFs share one parse path, one evidence model and one review UI.
-- -------------------------------------------------------------------------------------
CREATE TABLE document (
  id               NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id       NUMBER(19),                 -- NULL for a literature upload
  attachment_id    NUMBER(19),                 -- NULL for an email body
  source_kind      VARCHAR2(30) NOT NULL,
  filename         VARCHAR2(500),
  -- E9: content address. Parse results are cached against this, so the same PDF attached to
  -- two emails costs zero additional LLM calls.
  content_sha256   VARCHAR2(64),
  blob_path        VARCHAR2(1000),
  page_count       NUMBER(6)    DEFAULT 0 NOT NULL,
  -- E12: flavour is detected per page; these are roll-ups and MIXED is a legal value.
  doc_rendering    VARCHAR2(20),
  doc_genre        VARCHAR2(20),
  primary_language VARCHAR2(20),
  is_encrypted     CHAR(1)      DEFAULT 'N' NOT NULL,   -- E7
  truncated        CHAR(1)      DEFAULT 'N' NOT NULL,   -- E8
  parse_status     VARCHAR2(30) DEFAULT 'PENDING' NOT NULL,
  parse_error      VARCHAR2(2000),
  parse_ms         NUMBER(10),
  created_at       TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_document_message FOREIGN KEY (message_id)
    REFERENCES inbox_message (id) ON DELETE CASCADE,
  CONSTRAINT fk_document_attachment FOREIGN KEY (attachment_id)
    REFERENCES message_attachment (id) ON DELETE CASCADE,
  CONSTRAINT ck_document_kind CHECK (source_kind IN
    ('EMAIL_BODY','PDF_ATTACHMENT','IMAGE_ATTACHMENT','UPLOADED_ARTICLE')),
  CONSTRAINT ck_document_rendering CHECK (doc_rendering IS NULL OR doc_rendering IN
    ('DIGITAL','SCANNED','MIXED')),
  CONSTRAINT ck_document_genre CHECK (doc_genre IS NULL OR doc_genre IN
    ('FORM','ARTICLE','LETTER','MIXED')),
  CONSTRAINT ck_document_encrypted CHECK (is_encrypted IN ('Y','N')),
  CONSTRAINT ck_document_truncated CHECK (truncated IN ('Y','N')),
  -- PARSED and PARSE_FAILED are the two terminal states the E39 completion barrier waits for.
  CONSTRAINT ck_document_parse_status CHECK (parse_status IN
    ('PENDING','PARSING','PARSED','PARSE_FAILED'))
);

COMMENT ON TABLE document IS 'A parseable unit: an email body (E11), a PDF attachment, or an uploaded article.';


-- -------------------------------------------------------------------------------------
-- 4. DOCUMENT_PAGE — per-page flavour, text and the rendered image behind the UI overlay.
-- -------------------------------------------------------------------------------------
CREATE TABLE document_page (
  id              NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id     NUMBER(19)   NOT NULL,
  page_no         NUMBER(6)    NOT NULL,
  rendering       VARCHAR2(20),
  genre           VARCHAR2(20),
  language        VARCHAR2(20),
  lang_confidence NUMBER(5,4),
  char_count      NUMBER(10)   DEFAULT 0 NOT NULL,
  has_text_layer  CHAR(1)      DEFAULT 'N' NOT NULL,
  column_count    NUMBER(3)    DEFAULT 1 NOT NULL,     -- E14
  -- E16: the ORIGINAL is canonical. Every evidence quote and every character offset points
  -- here, never at the translation, because the original is the record of truth for audit.
  text_original   CLOB,
  text_english    CLOB,
  -- E34: vision transcription legibility, 0..1. Caps the confidence of every field sourced
  -- from this page, so handwriting uncertainty flows downstream instead of stopping at OCR.
  legibility      NUMBER(5,4)  DEFAULT 1 NOT NULL,
  width           NUMBER(10,2),
  height          NUMBER(10,2),
  rotation        NUMBER(6)    DEFAULT 0 NOT NULL,
  render_path     VARCHAR2(1000),
  -- Character-offset -> bounding-box index built at parse time (§10.3). This is what makes
  -- click-to-highlight possible without embedding a PDF renderer in the browser.
  span_index_json CLOB,
  CONSTRAINT fk_page_document FOREIGN KEY (document_id)
    REFERENCES document (id) ON DELETE CASCADE,
  CONSTRAINT uq_page_document_no UNIQUE (document_id, page_no),
  CONSTRAINT ck_page_rendering CHECK (rendering IS NULL OR rendering IN ('DIGITAL','SCANNED')),
  CONSTRAINT ck_page_genre CHECK (genre IS NULL OR genre IN ('FORM','ARTICLE','LETTER')),
  CONSTRAINT ck_page_text_layer CHECK (has_text_layer IN ('Y','N')),
  CONSTRAINT ck_page_legibility CHECK (legibility BETWEEN 0 AND 1)
);


-- -------------------------------------------------------------------------------------
-- 5. DOCUMENT_SECTION — heading segmentation, and the E15 exclusion that stops the model
--    manufacturing a "patient" out of a bibliography entry.
-- -------------------------------------------------------------------------------------
CREATE TABLE document_section (
  id                NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id       NUMBER(19)   NOT NULL,
  page_no           NUMBER(6)    NOT NULL,
  section_index     NUMBER(6)    DEFAULT 0 NOT NULL,
  heading           VARCHAR2(500),
  section_kind      VARCHAR2(40),
  char_start        NUMBER(10),
  char_end          NUMBER(10),
  -- E15: References / Acknowledgements / Conflict of interest / Funding are withheld from the
  -- extraction prompt but still feed the summary prompt.
  excluded_from_case CHAR(1)     DEFAULT 'N' NOT NULL,
  CONSTRAINT fk_section_document FOREIGN KEY (document_id)
    REFERENCES document (id) ON DELETE CASCADE,
  CONSTRAINT ck_section_excluded CHECK (excluded_from_case IN ('Y','N')),
  CONSTRAINT ck_section_kind CHECK (section_kind IS NULL OR section_kind IN (
    'TITLE','ABSTRACT','INTRODUCTION','METHODS','CASE_REPORT','RESULTS','DISCUSSION',
    'CONCLUSION','REFERENCES','ACKNOWLEDGEMENTS','CONFLICT_OF_INTEREST','FUNDING',
    'FORM_FIELDS','LETTER_BODY','OTHER'))
);


-- -------------------------------------------------------------------------------------
-- 6. DOCUMENT_TABLE — tables stay tables (R5). Headers and rows are stored as JSON arrays,
