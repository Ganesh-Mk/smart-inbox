  has_reporter          CHAR(1)     DEFAULT 'N' NOT NULL,
  reporter_confidence   NUMBER(5,4) DEFAULT 0 NOT NULL,
  reporter_evidence     VARCHAR2(2000),
  has_product           CHAR(1)     DEFAULT 'N' NOT NULL,
  product_confidence    NUMBER(5,4) DEFAULT 0 NOT NULL,
  product_evidence      VARCHAR2(2000),
  has_event             CHAR(1)     DEFAULT 'N' NOT NULL,
  event_confidence      NUMBER(5,4) DEFAULT 0 NOT NULL,
  event_evidence        VARCHAR2(2000),
  elements_present      NUMBER(2)   DEFAULT 0 NOT NULL,
  missing_elements_json VARCHAR2(500),
  CONSTRAINT fk_validity_classification FOREIGN KEY (classification_id)
    REFERENCES classification (id) ON DELETE CASCADE,
  CONSTRAINT ck_validity_patient  CHECK (has_patient  IN ('Y','N')),
  CONSTRAINT ck_validity_reporter CHECK (has_reporter IN ('Y','N')),
  CONSTRAINT ck_validity_product  CHECK (has_product  IN ('Y','N')),
  CONSTRAINT ck_validity_event    CHECK (has_event    IN ('Y','N'))
);


-- -------------------------------------------------------------------------------------
-- 11. CASE_RECORD — one extracted case. case_index exists from day one (E32), which is why
--     the literature bonus needs no schema change: one document can hold N cases.
-- -------------------------------------------------------------------------------------
CREATE TABLE case_record (
  id               NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id       NUMBER(19),
  document_id      NUMBER(19),
  case_index       NUMBER(6)    DEFAULT 0 NOT NULL,
  case_type        VARCHAR2(20) NOT NULL,
  patient_descriptor VARCHAR2(500),
  narrative        CLOB,
  -- E35: seriousness is the six regulatory criteria as independent booleans in JSON, not a
  -- severity slider and not free text.
  is_serious       CHAR(1)      DEFAULT 'N' NOT NULL,
  seriousness_json VARCHAR2(2000),
  confidence       NUMBER(5,4)  DEFAULT 0 NOT NULL,
  page_from        NUMBER(6),
  page_to          NUMBER(6),
  ai_call_id       NUMBER(19),
  created_at       TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_case_message FOREIGN KEY (message_id)
    REFERENCES inbox_message (id) ON DELETE CASCADE,
  CONSTRAINT fk_case_document FOREIGN KEY (document_id)
    REFERENCES document (id) ON DELETE CASCADE,
  CONSTRAINT ck_case_type CHECK (case_type IN ('ICSR','PQC','MI')),
  CONSTRAINT ck_case_serious CHECK (is_serious IN ('Y','N'))
);


-- -------------------------------------------------------------------------------------
-- 12. EXTRACTED_FIELD — one row per fact. Both the model's raw confidence and the final
--     adjusted value are stored, with the reason, so the write-up can show exactly how much
--     of a score is model self-report and how much is system verification (§11.5).
-- -------------------------------------------------------------------------------------
CREATE TABLE extracted_field (
  id                    NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_id               NUMBER(19)   NOT NULL,
  field_group           VARCHAR2(40) NOT NULL,
  field_path            VARCHAR2(200) NOT NULL,
  field_index           NUMBER(6)    DEFAULT 0 NOT NULL,   -- E31: arrays of products/reactions
  value_text            VARCHAR2(4000),
  value_json            CLOB,                              -- E28/E29/E30 typed values
  value_en              VARCHAR2(4000),                    -- E16 translation, never evidentiary
  unit                  VARCHAR2(40),
  raw_text              VARCHAR2(2000),                    -- E29: the source string is never destroyed
  status                VARCHAR2(20) DEFAULT 'NOT_STATED' NOT NULL,
  confidence            NUMBER(5,4)  DEFAULT 0 NOT NULL,
  confidence_pre_adjust NUMBER(5,4),
  adjust_reason         VARCHAR2(500),
  decided_by            VARCHAR2(20) DEFAULT 'AI' NOT NULL,
  decided_by_user       VARCHAR2(200),
  superseded_by         NUMBER(19),                        -- E40 append-only override
  created_at            TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_field_case FOREIGN KEY (case_id)
    REFERENCES case_record (id) ON DELETE CASCADE,
  CONSTRAINT fk_field_superseded FOREIGN KEY (superseded_by)
    REFERENCES extracted_field (id),
  -- NOT_STATED is a first-class answer, never an error state (CLAUDE.md constraint 4).
  CONSTRAINT ck_field_status CHECK (status IN ('STATED','NOT_STATED','UNCERTAIN','CONFLICT')),
  CONSTRAINT ck_field_conf CHECK (confidence BETWEEN 0 AND 1),
  CONSTRAINT ck_field_decided CHECK (decided_by IN ('AI','REVIEWER','RULE'))
);


-- -------------------------------------------------------------------------------------
-- 13. FIELD_EVIDENCE — the differentiator (E27). VERIFIED is written by pipeline/verify.py
--     after it proves the quote occurs in the page text. A model-asserted citation that
--     cannot be proved lands here as verified='N' and caps the field's confidence at 0.40.
-- -------------------------------------------------------------------------------------
CREATE TABLE field_evidence (
  id            NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  field_id      NUMBER(19)   NOT NULL,
  source_type   VARCHAR2(20) NOT NULL,
  document_id   NUMBER(19),
  page_no       NUMBER(6),
  quote         VARCHAR2(4000),
  -- Offsets are REWRITTEN by the verifier to the real position found in the source; the
  -- model's own numbers are never kept.
  char_start    NUMBER(10),
  char_end      NUMBER(10),
  bbox          VARCHAR2(200),
  verified      CHAR(1)      DEFAULT 'N' NOT NULL,
  verify_method VARCHAR2(20) DEFAULT 'FAILED' NOT NULL,
  match_score   NUMBER(6,2),
  created_at    TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_evidence_field FOREIGN KEY (field_id)
    REFERENCES extracted_field (id) ON DELETE CASCADE,
  CONSTRAINT fk_evidence_document FOREIGN KEY (document_id)
    REFERENCES document (id) ON DELETE CASCADE,
  CONSTRAINT ck_evidence_source CHECK (source_type IN ('EMAIL_BODY','PDF_PAGE','TABLE','IMAGE')),
  CONSTRAINT ck_evidence_verified CHECK (verified IN ('Y','N')),
  CONSTRAINT ck_evidence_method CHECK (verify_method IN ('EXACT','FUZZY','FAILED'))
);

COMMENT ON TABLE field_evidence IS
  'Machine-verified provenance. verified=Y means code found the quote in the source, not that the model claimed it.';


-- -------------------------------------------------------------------------------------
-- 14. JOB — the durable work queue. Dequeued with FOR UPDATE SKIP LOCKED by PKG_JOB_QUEUE,
--     so the pipeline is asynchronous and restart-safe (R18, E37, E38).
-- -------------------------------------------------------------------------------------
CREATE TABLE job (
  id            NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_type      VARCHAR2(40) NOT NULL,
  subject_type  VARCHAR2(20) NOT NULL,
  subject_id    NUMBER(19)   NOT NULL,
  state         VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
  priority      NUMBER(3)    DEFAULT 5 NOT NULL,
  attempts      NUMBER(4)    DEFAULT 0 NOT NULL,
  max_attempts  NUMBER(4)    DEFAULT 3 NOT NULL,
  available_at  TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  locked_by     VARCHAR2(100),
  locked_at     TIMESTAMP(6) WITH TIME ZONE,
  last_error    VARCHAR2(4000),
  payload_json  VARCHAR2(4000),
  created_at    TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at    TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_job_type CHECK (job_type IN (
    'PARSE_DOCUMENT','CLASSIFY_MESSAGE','EXTRACT_CASE','FINALISE_MESSAGE','SCREEN_ARTICLE')),
  CONSTRAINT ck_job_state CHECK (state IN ('PENDING','RUNNING','DONE','FAILED','DEAD')),
  CONSTRAINT ck_job_subject CHECK (subject_type IN ('MESSAGE','DOCUMENT','BATCH'))
);


-- -------------------------------------------------------------------------------------
-- 15. AI_CALL_LOG — R15. The exact request and response behind every AI decision, with the
--     prompt version, token counts, measured dollar cost and latency. GET /api/ai-calls/{id}
