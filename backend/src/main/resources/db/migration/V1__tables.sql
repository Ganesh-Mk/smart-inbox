-- -------------------------------------------------------------------------------------
-- 9. CLASSIFICATION — multi-label, one row per label (E23/E24: labels are independent
--    booleans, never a softmax). Classified at both levels (E25): each document, and the
--    message as the union.
-- -------------------------------------------------------------------------------------
CREATE TABLE classification (
  id             NUMBER(19)   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_type   VARCHAR2(20) NOT NULL,
  subject_id     NUMBER(19)   NOT NULL,
  category       VARCHAR2(30) NOT NULL,
  confidence     NUMBER(5,4)  DEFAULT 0 NOT NULL,
  reason         VARCHAR2(2000),
  -- The unit that triggered this label when rolled up to message level (E25).
  triggered_by_document_id NUMBER(19),
  decided_by     VARCHAR2(20) DEFAULT 'AI' NOT NULL,
  decided_by_user VARCHAR2(200),
  -- E40: an override never updates this row; it inserts a new one and points here.
  superseded_by  NUMBER(19),
  model          VARCHAR2(100),
  prompt_version VARCHAR2(40),
  ai_call_id     NUMBER(19),
  created_at     TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_classification_subject CHECK (subject_type IN ('MESSAGE','DOCUMENT')),
  CONSTRAINT ck_classification_category CHECK (category IN
    ('ICSR','ICSR_INCOMPLETE','PQC','MI','NOT_RELEVANT')),
  CONSTRAINT ck_classification_decided CHECK (decided_by IN ('AI','REVIEWER','RULE')),
  CONSTRAINT ck_classification_conf CHECK (confidence BETWEEN 0 AND 1),
  CONSTRAINT fk_classification_superseded FOREIGN KEY (superseded_by)
    REFERENCES classification (id)
);


-- -------------------------------------------------------------------------------------
-- 10. ICSR_VALIDITY — E22. The model reports the four minimum criteria as an explicit
